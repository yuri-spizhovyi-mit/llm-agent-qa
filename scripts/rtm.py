"""Requirements traceability matrix: requirement -> tests, read from the tests themselves.

    python scripts/rtm.py            # write docs/rtm.csv and docs/rtm.md; exit 1 on a gap
    python scripts/rtm.py --check    # verify only (ENV-05 runs this in CI)

Links come from `@pytest.mark.req("ID", ...)` on each test function in `tests/test_*.py`, or
from a module-level `pytestmark` (never a hand-kept list). The catalogue,
`docs/requirements.csv`, says what each ID means. The check fails when:
- a catalogued requirement has no test;
- a test cites an ID that isn't catalogued, or cites none;
- `docs/rtm.csv` or `docs/rtm.md` is out of date.
A parametrized test counts once. The matrix follows the one in vendor/settlement.
"""

from __future__ import annotations

import argparse
import ast
import csv
import io
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOGUE = ROOT / "docs" / "requirements.csv"
RTM_CSV = ROOT / "docs" / "rtm.csv"
RTM_MD = ROOT / "docs" / "rtm.md"


def _req_ids(nodes) -> list[str]:
    """IDs in `pytest.mark.req(...)` calls among decorator or pytestmark nodes."""
    ids = []
    for node in nodes:
        if isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "req":
            ids += [a.value for a in node.args if isinstance(a, ast.Constant) and isinstance(a.value, str)]
    return ids


def links(tests_dir: Path = ROOT / "tests") -> tuple[dict[str, list[str]], list[str]]:
    """{requirement ID: [test ids]} and the tests that cite no requirement."""
    found: dict[str, list[str]] = defaultdict(list)
    untraced = []
    for path in sorted(tests_dir.glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        module: list[str] = []
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "pytestmark" for t in node.targets):
                value = node.value
                module += _req_ids(value.elts if isinstance(value, (ast.List, ast.Tuple)) else [value])
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                test_id = f"tests/{path.name}::{node.name}"
                ids = _req_ids(node.decorator_list) or module
                if not ids:
                    untraced.append(test_id)
                for req in dict.fromkeys(ids):
                    found[req].append(test_id)
    return found, untraced


def catalogue() -> list[dict]:
    with CATALOGUE.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def problems(rows: list[dict], found: dict[str, list[str]], untraced: list[str]) -> list[str]:
    known = {r["id"] for r in rows}
    out = [f"{r['id']} has no test" for r in rows if not found.get(r["id"])]
    out += [f"{req} is cited by {', '.join(tests)} but not catalogued in docs/requirements.csv"
            for req, tests in sorted(found.items()) if req not in known]
    out += [f"{t} cites no requirement" for t in untraced]
    return out


def render_csv(rows: list[dict], found: dict[str, list[str]]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(["id", "area", "risk", "requirement", "tests", "test_ids"])
    for r in rows:
        tests = found.get(r["id"], [])
        writer.writerow([r["id"], r["area"], r["risk"], r["requirement"], len(tests), "; ".join(tests)])
    return buffer.getvalue()


def render_md(rows: list[dict], found: dict[str, list[str]]) -> str:
    total = sum(len(found.get(r["id"], [])) for r in rows)
    traced = sum(bool(found.get(r["id"])) for r in rows)
    areas: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        areas[r["area"]].append(r)
    lines = [
        "# Requirements traceability matrix", "",
        "Generated by `scripts/rtm.py` from the tests themselves (`@pytest.mark.req`); do not edit by",
        "hand. CI fails if a requirement has no test, a test cites an unknown requirement or none, or",
        "this file is stale (ENV-05). Full test lists: [`rtm.csv`](rtm.csv). The requirements:",
        "[`requirements.csv`](requirements.csv).", "",
        f"**{len(rows)} requirements, {traced} traced: {total} requirement-test links.**", "",
        "| Area | Requirements | Links | High-risk |", "|---|---|---|---|",
    ]
    for area, group in areas.items():
        links_ = sum(len(found.get(r["id"], [])) for r in group)
        high = sum(r["risk"] == "high" for r in group)
        lines.append(f"| {area} | {len(group)} | {links_} | {high} |")
    lines += ["", "| ID | Risk | Requirement | Tests |", "|---|---|---|---|"]
    for r in rows:
        tests = found.get(r["id"], [])
        names = "<br>".join(f"`{t.split('::')[1]}`" for t in tests) or "**none**"
        lines.append(f"| {r['id']} | {r['risk']} | {r['requirement']} | {names} |")
    return "\n".join(lines) + "\n"


def check() -> list[str]:
    """Everything wrong with the traceability, as messages; empty when it's complete and current."""
    rows = catalogue()
    found, untraced = links()
    out = problems(rows, found, untraced)
    for path, text in ((RTM_CSV, render_csv(rows, found)), (RTM_MD, render_md(rows, found))):
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            out.append(f"{path.relative_to(ROOT).as_posix()} is stale: run python scripts/rtm.py")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="verify only; write nothing")
    args = parser.parse_args(argv)
    if not args.check:
        rows = catalogue()
        found, _ = links()
        RTM_CSV.write_bytes(render_csv(rows, found).encode("utf-8"))
        RTM_MD.write_bytes(render_md(rows, found).encode("utf-8"))
    issues = check()
    for issue in issues:
        print(issue, file=sys.stderr)
    if not issues:
        print(f"traceability complete: {len(catalogue())} requirements, rtm up to date")
    return 1 if issues else 0


if __name__ == "__main__":
    raise SystemExit(main())
